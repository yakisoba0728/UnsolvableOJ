// Read an immutable Git revision; no application services or credentials required.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from '../Back/node_modules/typescript/lib/typescript.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
const revision = git('rev-parse', '--verify', `${process.argv[2] ?? 'HEAD'}^{commit}`).trim();
const files = git('ls-tree', '-rz', '--name-only', revision).split('\0').filter(Boolean);
const read = (path) => git('show', `${revision}:${path}`);
const decorators = (node) => ts.canHaveDecorators(node) ? ts.getDecorators(node) ?? [] : [];
const calls = (node, source) => decorators(node).flatMap(({ expression }) => ts.isCallExpression(expression)
  ? [{ name: expression.expression.getText(source), args: [...expression.arguments] }] : []);
const values = (node) => !node ? [''] : ts.isArrayLiteralExpression(node)
  ? node.elements.flatMap(values) : ts.isStringLiteralLike(node) ? [node.text] : [node.getText()];
const apis = [];

for (const file of files.filter((path) => path.endsWith('.controller.ts'))) {
  const source = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true);
  for (const declaration of source.statements.filter(ts.isClassDeclaration)) {
    const classCalls = calls(declaration, source);
    const controller = classCalls.find((call) => call.name === 'Controller');
    if (!controller) continue;
    for (const member of declaration.members.filter(ts.isMethodDeclaration)) {
      const methodCalls = calls(member, source);
      const endpoint = methodCalls.find((call) => ['Get', 'Post', 'Put', 'Patch', 'Delete', 'Options', 'Head', 'All'].includes(call.name));
      if (!endpoint) continue;
      const guards = [...classCalls, ...methodCalls].filter((call) => call.name === 'UseGuards').flatMap((call) => call.args.map((arg) => arg.getText(source)));
      const roles = (methodCalls.find((call) => call.name === 'Roles') ?? classCalls.find((call) => call.name === 'Roles'))?.args.map((arg) => arg.getText(source)) ?? [];
      for (const prefix of values(controller.args[0])) for (const suffix of values(endpoint.args[0])) {
        apis.push({ method: endpoint.name.toUpperCase(), path: `/api/v1/${prefix}/${suffix}`.replace(/\/+/g, '/').replace(/\/$/, ''), controller: declaration.name.text, handler: member.name.getText(source), guards, roles, source: file });
      }
    }
  }
}
apis.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const migrations = files.filter((path) => /^Back\/src\/database\/migrations\//.test(path));
const tables = [];
for (const file of migrations) {
  for (const match of read(file).matchAll(/CREATE TABLE\s+(?:IF NOT EXISTS\s+)?["`]?([a-z_][a-z0-9_]*)/gi)) tables.push({ name: match[1], migration: file });
}
const routes = [...read('Front/src/App.tsx').matchAll(/\bpath="([^"]+)"/g)].map((match) => match[1]);
const tests = files.filter((path) => /(?:\.spec\.ts|\.test\.[cm]?[jt]s|\.(?:e2e|pipeline)-spec\.ts|\/test_[^/]+\.py)$/.test(path));
const packages = ['Back', 'Front', 'Judge'].map((part) => {
  const manifest = JSON.parse(read(`${part}/package.json`));
  return { path: part, name: manifest.name, license: manifest.license ?? 'not declared', scripts: manifest.scripts, dependencies: manifest.dependencies, devDependencies: manifest.devDependencies };
});
const inventory = {
  revision,
  scope: 'Static inventory at an exact revision; counts are not test coverage or an assertion that all behavior is verified.',
  fileCount: files.length,
  byTopLevel: files.reduce((counts, path) => { const key = path.includes('/') ? path.split('/')[0] : '(root)'; counts[key] = (counts[key] ?? 0) + 1; return counts; }, {}),
  controllers: [...new Set(apis.map((api) => api.source))],
  apiCount: apis.length, apis,
  frontendRoutes: routes,
  migrationCount: migrations.length, migrations, tables,
  testFileCount: tests.length, tests, packages,
};
const directory = new URL('../docs/overhaul/', import.meta.url);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL('INVENTORY.json', directory), JSON.stringify(inventory, null, 2) + '\n');
writeFileSync(new URL('API.md', directory), `# API inventory\n\nRevision: \`${revision}\`. Generated by \`node scripts/overhaul-inventory.mjs ${revision}\`.\n\n${apis.length} route/method combinations. Guards listed below are controller decorators; service-level ownership checks and the global throttler are additional boundaries. An absent decorator does not establish a vulnerability. Swagger is separately mounted at /docs.\n\n| Method | Path | Handler | Guards | Roles |\n|---|---|---|---|---|\n` + apis.map((api) => `| ${api.method} | \`${api.path}\` | ${api.controller}.${api.handler} | ${api.guards.join(', ') || 'none'} | ${api.roles.join(', ') || '—'} |`).join('\n') + '\n');
console.log(JSON.stringify({ revision, files: files.length, controllers: inventory.controllers.length, endpoints: apis.length, frontendRoutes: routes.length, tables: tables.length, migrations: migrations.length, testFiles: tests.length }));
