/**
 * 자동완성 데이터. 항목은 한 줄 문자열로 적는다.
 *   "name(sig)|설명"   함수·메서드 (괄호가 있으면 호출형)
 *   "name|설명"        속성·상수
 *   "c:Name<T>|설명"   클래스·타입 (<가 있으면 제네릭 괄호를 함께 넣는다)
 */

export type SuggestionKind =
  | "snippet"
  | "keyword"
  | "function"
  | "method"
  | "property"
  | "class"
  | "variable"
  | "module"
  | "word";

export interface Suggestion {
  /** 목록에 보이는 이름 */
  label: string;
  /** 실제로 넣을 글. `$0`은 마지막 커서, `${1:이름}`·`$1`은 Tab으로 옮겨 다니는 자리다. */
  insert: string;
  kind: SuggestionKind;
  /** 이름 오른쪽에 작게 보이는 시그니처·설명 */
  detail?: string;
  /** 선택했을 때 아래 설명 칸에 보이는 글 */
  doc?: string;
  /** label에서 입력과 맞은 글자 위치(강조용) */
  matches?: number[];
}

const words = (text: string) => text.split(/\s+/).filter(Boolean);

function entry(
  raw: string,
  owner: string | undefined,
  callKind: SuggestionKind,
): Suggestion {
  const [head, doc] = raw.split("|");
  const isClass = head.startsWith("c:");
  const body = isClass ? head.slice(2) : head;
  const open = body.search(/[(<]/);
  const label = open < 0 ? body : body.slice(0, open);
  const tail = open < 0 ? "" : body.slice(open);
  let insert = label;
  const kind: SuggestionKind = isClass
    ? "class"
    : open < 0
      ? "property"
      : callKind;
  if (tail.startsWith("<")) insert = `${label}<$0>`;
  else if (tail.startsWith("("))
    insert = tail === "()" ? `${label}()` : `${label}($0)`;
  return {
    label,
    insert,
    kind,
    detail: tail || undefined,
    doc: [doc, owner].filter(Boolean).join(" · ") || undefined,
  };
}

const list = (
  owner: string | undefined,
  entries: string[],
  callKind: SuggestionKind = "method",
) => entries.map((raw) => entry(raw, owner, callKind));

